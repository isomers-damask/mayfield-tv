"""Build content/live.json for the TV from settings, the evergreen library, and one reviewed week.

  python3 tools/publish.py --week 2026-W44 --review review_export.json

review_export.json: {"items": [...candidates...], "decisions": {id: {"d": "approve|fix|cut", "edits": {...}, "n": "note", "resolved": bool}},
                     "settings": {...optional overrides from the review page...}}
Approved items go live. "fix" items go live only when their edits are marked resolved. Cut items never do.
Evergreen approved items join content/library.json so they come back in later weeks.
"""
import json, argparse, datetime, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
C = ROOT / "content"
TEXT = ["eyebrow", "headline", "body", "card", "line", "caption", "myth", "fact", "question", "answer", "event", "title", "text"]
LIMITS = {"headline": 70, "body": 190, "card": 100, "line": 110, "myth": 120, "fact": 120, "answer": 240, "title": 40, "text": 130}
BANNED = [r"—", r"!", r"\bguarantee", r"\bcure[sd]?\b", r"\bpain-free\b", r"\bunlock\b", r"\bjourney\b", r"\btransform", r"Mayfield Advanced Medical", r"\bMAM\b"]

def problems(it):
    out = []
    vals = [it.get(k) or "" for k in TEXT] + list(it.get("steps") or []) + list(it.get("items") or []) + list(it.get("points") or [])
    blob = " ".join(map(str, vals))
    for b in BANNED:
        if re.search(b, blob, re.I): out.append("banned: " + b)
    for k, n in LIMITS.items():
        if len(str(it.get(k) or "")) > n: out.append(f"{k} over {n} chars")
    if it.get("zone") == "crawler" and len(str(it.get("line") or it.get("text") or "")) > 120: out.append("crawler line too long")
    return out

def week_of(d):
    y, w, _ = d.isocalendar(); return f"{y}-W{w:02d}"

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--week", required=True); ap.add_argument("--review", required=True)
    ap.add_argument("--today", default=datetime.date.today().isoformat()); a = ap.parse_args()
    settings = json.load(open(C / "settings.json"))
    lib = json.load(open(C / "library.json"))
    rev = json.load(open(a.review))
    settings.update(rev.get("settings") or {})
    dec = rev.get("decisions") or {}

    live_items, held, report = [], [], []
    for it in rev.get("items", []):
        d = dec.get(it["id"], {})
        choice = d.get("d")
        if choice == "cut" or not choice: continue
        it = dict(it); it.update(d.get("edits") or {})
        if choice == "fix" and not d.get("resolved"): held.append(it["id"]); continue
        p = problems(it)
        if p: held.append(it["id"]); report.append(f"{it['id']}: " + "; ".join(p)); continue
        it["week"] = a.week; live_items.append(it)

    main_new = [i for i in live_items if i.get("zone") == "main"]
    side_new = [i for i in live_items if i.get("zone") == "side"]
    crawl_new = [i for i in live_items if i.get("zone") == "crawler"]

    # evergreen approved items join the library (news and date-bound items don't)
    have = {i["id"] for i in lib["items"]}
    for i in main_new + side_new:
        if i["id"] in have or i.get("category") == "news" or i.get("show_until") or i.get("date"): continue
        j = dict(i); j["added"] = a.today; lib["items"].append(j)

    # fill the loop from the library, skipping anything shown in the last two weeks
    recent = {a.week}
    wk = datetime.date.fromisoformat(a.today)
    for k in (1, 2): recent.add(week_of(wk - datetime.timedelta(weeks=k)))
    target = int(settings.get("loopTarget", 48))
    new_ids = {i["id"] for i in main_new}
    lib_main = [i for i in lib["items"] if i.get("zone", "main") == "main" and i["id"] not in new_ids and not i.get("retired")]
    fresh = [i for i in lib_main if i.get("last_week") not in recent]
    stale = [i for i in lib_main if i.get("last_week") in recent]
    fill = (fresh + stale)[: max(0, target - len(main_new))]
    for i in fill: i["last_week"] = a.week
    lib_side = [i for i in lib["items"] if i.get("zone") == "side" and i["id"] not in {s["id"] for s in side_new} and not i.get("retired")][:6]

    live = {
        "version": a.week, "published": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "settings": {k: settings[k] for k in ("location", "videoEveryMinutes", "hours") if k in settings},
        "standing_crawler": settings.get("standing_crawler", []),
        "videos": settings.get("videos", []), "backgrounds": settings.get("backgrounds", {}), "spots": settings.get("spots", []),
        "main": main_new + fill, "side": side_new + lib_side, "crawler": crawl_new,
    }
    json.dump(live, open(C / "live.json", "w"), indent=1, ensure_ascii=False)
    (C / "fallback.js").write_text("/* Last published content, used when the TV can't reach the internet. Generated by tools/publish.py */\nwindow.TV_FALLBACK = " + json.dumps(live, ensure_ascii=False) + ";\n")
    json.dump(lib, open(C / "library.json", "w"), indent=1, ensure_ascii=False)
    s = json.load(open(C / "settings.json")); s.update(rev.get("settings") or {}); json.dump(s, open(C / "settings.json", "w"), indent=1, ensure_ascii=False)
    summary = {"week": a.week, "main_new": len(main_new), "main_library": len(fill), "side": len(live["side"]), "crawler": len(crawl_new),
               "held": held, "problems": report, "library_size": len(lib["items"])}
    print(json.dumps(summary, indent=1))
    return 0

if __name__ == "__main__": sys.exit(main())
