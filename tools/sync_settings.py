"""Push settings-only changes (spots, videos, backgrounds, standing crawler, hours) to the TV without publishing a new week.
   python3 tools/sync_settings.py"""
import json, pathlib, datetime
C = pathlib.Path(__file__).resolve().parent.parent / "content"
s = json.load(open(C / "settings.json")); live = json.load(open(C / "live.json"))
live["settings"] = {k: s[k] for k in ("location", "videoEveryMinutes", "hours") if k in s}
for k in ("standing_crawler", "videos", "backgrounds", "spots"): live[k] = s.get(k, [] if k != "backgrounds" else {})
live["published"] = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
json.dump(live, open(C / "live.json", "w"), indent=1, ensure_ascii=False)
(C / "fallback.js").write_text("/* Last published content, used when the TV can't reach the internet. Generated by tools/ */\nwindow.TV_FALLBACK = " + json.dumps(live, ensure_ascii=False) + ";\n")
print("live.json updated:", {k: (len(v) if hasattr(v, "__len__") else v) for k, v in live.items() if k in ("main", "side", "crawler", "videos", "spots", "backgrounds")})
